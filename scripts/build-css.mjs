import { execFileSync, spawn } from "node:child_process";
import {
    existsSync,
    mkdirSync,
    readFileSync,
    watch,
    writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CLI = join(ROOT, "node_modules", ".bin", "tailwindcss");
const INPUT = join(ROOT, "webview", "panel.css");
const OUT = join(ROOT, "src", "panel-css.ts");
const WATCH_DIR = join(ROOT, "dist");
const WATCH_FILE = "panel.css";

function writeModule(css) {
    // Committed because the publishing service builds src/index.ts with esbuild and runs no CSS step.
    const source =
        `// Generated by scripts/build-css.mjs. Do not edit by hand.\n` +
        `export const PANEL_CSS = ${JSON.stringify(css.trim())};\n`;
    // Skipping identical writes keeps a second build from dirtying the tree and the dev server from looping.
    if (existsSync(OUT) && readFileSync(OUT, "utf8") === source) return;
    writeFileSync(OUT, source);
}

if (!process.argv.includes("--watch")) {
    writeModule(
        execFileSync(CLI, ["-i", INPUT, "--minify"], {
            cwd: ROOT,
            encoding: "utf8",
            stdio: ["ignore", "pipe", "inherit"],
        })
    );
} else {
    mkdirSync(WATCH_DIR, { recursive: true });
    // "always" because stdin is not passed on: the CLI would read it and steal Vite's shortcut keys.
    const cli = spawn(
        CLI,
        [
            "-i",
            INPUT,
            "--minify",
            "--watch=always",
            "-o",
            join(WATCH_DIR, WATCH_FILE),
        ],
        { cwd: ROOT, stdio: ["ignore", "inherit", "inherit"] }
    );
    const watcher = watch(WATCH_DIR, (_event, name) => {
        if (name !== WATCH_FILE) return;
        const path = join(WATCH_DIR, WATCH_FILE);
        if (existsSync(path)) writeModule(readFileSync(path, "utf8"));
    });
    for (const signal of ["SIGINT", "SIGTERM"]) {
        process.on(signal, () => cli.kill(signal));
    }
    cli.on("exit", (code) => {
        watcher.close();
        process.exit(code ?? 0);
    });
}
